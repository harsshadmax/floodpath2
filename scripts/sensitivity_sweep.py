"""Sensitivity sweep over the edge-classification thresholds (required-changes PDF, Section 2).

The flood-aware routing results depend on three assumed, unmeasured thresholds:
  FLOOD_FRACTION_AT_RISK (0.10), FLOOD_FRACTION_BLOCKED (0.50), AT_RISK_TIME_MULTIPLIER (3.0x).
This sweep re-runs the moderate and severe scenarios under alternative settings so the demo can show
which conclusions hold across the plausible range, instead of only the one setting currently shipped.

Usage: python scripts/sensitivity_sweep.py   (needs data/processed from build_phase2/3; takes ~1-2 min)
Writes docs/SENSITIVITY.md.
"""
import dataclasses
import sys
import time
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from config import CONFIG  # noqa: E402
from src import facilities as fac  # noqa: E402
from src import flood, metrics, roads, wards  # noqa: E402

PROCESSED = ROOT / "data" / "processed"
OUT = ROOT / "docs" / "SENSITIVITY.md"

# (at_risk threshold, blocked threshold, at-risk time multiplier)
SETTINGS = [
    (0.10, 0.50, 3.0),   # shipped default
    (0.05, 0.35, 3.0),   # more cautious: less flooding needed to block a road
    (0.20, 0.65, 3.0),   # more lenient: more flooding needed to block a road
    (0.10, 0.50, 2.0),   # a milder at-risk delay
    (0.10, 0.50, 5.0),   # a harsher at-risk delay
]


def main() -> None:
    t0 = time.time()
    G = roads.load_graph()
    suitable, _ = fac.suitable_facilities(fac.load_facilities(), G)
    origins = pd.read_csv(PROCESSED / "origins.csv")
    _, _, _, geoms = flood.routed_scenarios()

    rows = []
    for name in ("moderate", "severe"):
        geom = geoms[name]
        for at_risk, blocked, mult in SETTINGS:
            cfg = dataclasses.replace(
                CONFIG,
                FLOOD_FRACTION_AT_RISK=at_risk,
                FLOOD_FRACTION_BLOCKED=blocked,
                AT_RISK_TIME_MULTIPLIER=mult,
            )
            _, results = metrics.route_all(G, geom, origins, suitable, cfg)
            m = metrics.scenario_metrics(results, origins, suitable, cfg)
            rows.append({
                "scenario": name, "at_risk_threshold": at_risk, "blocked_threshold": blocked,
                "at_risk_multiplier": mult,
                "m3_reach_any": m["m3_reach_any"], "m4_coverage_flood_aware": m["m4_coverage_flood_aware"],
                "m1_mean_extra_min": m["m1_time_increase_min"]["mean"],
            })
            print(rows[-1], flush=True)

    df = pd.DataFrame(rows)
    lines = [
        "# Sensitivity sweep over the edge-classification thresholds",
        "",
        "Generated by `scripts/sensitivity_sweep.py`. The shipped settings are "
        f"FLOOD_FRACTION_AT_RISK={CONFIG.FLOOD_FRACTION_AT_RISK}, "
        f"FLOOD_FRACTION_BLOCKED={CONFIG.FLOOD_FRACTION_BLOCKED}, "
        f"AT_RISK_TIME_MULTIPLIER={CONFIG.AT_RISK_TIME_MULTIPLIER} (first row of each scenario below).",
        "All other settings (flood geometry, origins, facilities) are held fixed; only the three",
        "thresholds change. Read this as: do the headline conclusions (which facilities are cut off,",
        "roughly what share of origins reach one) survive a plausible change to these assumptions?",
        "",
    ]
    for name in ("moderate", "severe"):
        lines.append(f"## {name}")
        lines.append("")
        lines.append("| at_risk | blocked | x-multiplier | reach-any | coverage-30min | mean extra min |")
        lines.append("|---|---|---|---|---|---|")
        for r in rows:
            if r["scenario"] != name:
                continue
            lines.append(
                f"| {r['at_risk_threshold']} | {r['blocked_threshold']} | {r['at_risk_multiplier']} | "
                f"{r['m3_reach_any']:.3f} | {r['m4_coverage_flood_aware']:.3f} | "
                f"{r['m1_mean_extra_min'] if r['m1_mean_extra_min'] is not None else 'n/a'} |"
            )
        lines.append("")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} in {time.time() - t0:.0f}s")


if __name__ == "__main__":
    main()
